# PART 2: THE EVALUATORS (The Graders)
# ==========================================
judge_llm = ChatGroq(model_name="llama-3.1-8b-instant", temperature=0)

class JudgeScore(BaseModel):
    helpfulness_score: float = Field(description="Score between 0.0 and 1.0. (e.g. 0.9 for great, 0.2 for bad)")
    reasoning: str = Field(description="Why the judge gave this score.")

judge_prompt = ChatPromptTemplate.from_messages([
    ("system", "You are an Expert AI Evaluator grading an AI Interview Coach."),
    ("user", """
    Candidate's Answers: {user_answers}
    
    Expected Verdict from Dataset: {expected_verdict}
    Expected Feedback from Dataset: {expected_feedback}
    
    Actual Feedback generated by the AI Coach: {actual_feedback}
    
    Evaluate the AI Coach. Did it give a verdict similar to the expected one? Rate its helpfulness and accuracy on a scale of 0.0 to 1.0.
    """)
])

judge_chain = judge_prompt | judge_llm.with_structured_output(JudgeScore)

def llm_judge(run, example):
    """This function compares  AI's output against the expected dataset output."""
    
    actual_feedback = run.outputs
    expected_verdict = example.outputs["expected_verdict"]
    expected_feedback = example.outputs["expected_feedback"]
    user_answers = example.inputs["user_answers"]
    
    judge_result = judge_chain.invoke({
        "user_answers": user_answers,
        "expected_verdict": expected_verdict,
        "expected_feedback": expected_feedback,
        "actual_feedback": str(actual_feedback)
    })
    
    return {
        "key": "AI_Coach_Quality_Score",
        "score": judge_result.helpfulness_score,
        "comment": judge_result.reasoning
    }

def tone_evaluator(run, example):
    """A deterministic check to evaluate if the tone is professional."""
    actual_feedback = str(run.outputs).lower()
    
    # Simple keyword check: A professional coach should not be insulting
    is_polite = "terrible" not in actual_feedback and "idiot" not in actual_feedback
    
    return {
        "key": "Professional_Tone_Score", 
        "score": 1 if is_polite else 0,
        "comment": "Checked if feedback contained unprofessional keywords."
    }

def accuracy_evaluator(run, example):
    """A deterministic check to see if the AI gave the exact verdict."""
    
    # 1. Get the AI's verdict, convert to lowercase, and strip invisible spaces
    actual_feedback = run.outputs
    actual_verdict = str(actual_feedback.get("verdict", "")).lower().strip()
    
    # 2. Get the expected verdict, lowercase, and strip spaces
    expected_verdict = str(example.outputs["expected_verdict"]).lower().strip()
    
    # 3. STRICT EXACT MATCH: They must be completely identical
    is_match = (actual_verdict == expected_verdict)
    
    return {
        "key": "Verdict_Accuracy", 
        "score": 1 if is_match else 0,
        "comment": f"Expected: '{expected_verdict}' | AI Output: '{actual_verdict}'"
    }


